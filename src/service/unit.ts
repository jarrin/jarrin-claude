/**
 * The systemd unit for the claudjar service.
 *
 * A **system** unit with `User=` (rather than a `systemctl --user` unit) so it is
 * declared once in `/etc`, beside `/etc/claudjar.conf` which names that user. It
 * keeps the default `KillMode`: the session launcher already wraps every spawn in
 * `systemd-run --user --scope`, so background sessions live in their own cgroup
 * and survive a stop or restart of this unit (Stage 1's decision).
 *
 * That scope lives in the user's own systemd manager, reached through
 * `XDG_RUNTIME_DIR` — set here because a system unit gets no login session.
 * Without lingering that manager only runs while the user is logged in, which is
 * why `service status` reports linger.
 */

export const UNIT_NAME = "claudjar.service";
export const UNIT_PATH = `/etc/systemd/system/${UNIT_NAME}`;

export interface UnitParams {
  readonly user: string;
  readonly uid: number;
  readonly home: string;
  /** Absolute path of the claudjar executable the unit runs. */
  readonly bin: string;
  readonly confPath: string;
}

/** Escape systemd's `%` specifiers, which it expands in most unit settings. */
function pct(s: string): string {
  return s.replace(/%/g, "%%");
}

/** A systemd command-line word: quoted when it holds whitespace or quotes. */
function word(s: string): string {
  const v = pct(s);
  return /^[^\s"'\\]+$/.test(v) ? v : `"${v.replace(/(["\\])/g, "\\$1")}"`;
}

/** A quoted `Environment=` assignment, safe for any value. */
function env(key: string, value: string): string {
  return `Environment="${key}=${pct(value).replace(/(["\\])/g, "\\$1")}"`;
}

export function renderUnit(p: UnitParams): string {
  const path = [
    `${p.home}/.local/bin`,
    "/usr/local/sbin",
    "/usr/local/bin",
    "/usr/bin",
  ].join(":");
  return [
    "# Generated by `claudjar service install` — rerun it instead of editing.",
    "[Unit]",
    "Description=claudjar service (projects, background Claude sessions)",
    "Wants=network-online.target",
    "After=network-online.target",
    "",
    "[Service]",
    "Type=simple",
    `User=${p.user}`,
    `WorkingDirectory=${word(p.home)}`,
    env("HOME", p.home),
    env("XDG_RUNTIME_DIR", `/run/user/${String(p.uid)}`),
    env("PATH", path),
    env("CLAUDJAR_CONF", p.confPath),
    `ExecStart=${word(p.bin)} service run`,
    "Restart=on-failure",
    "RestartSec=5",
    "",
    "[Install]",
    "WantedBy=multi-user.target",
    "",
  ].join("\n");
}

export interface Passwd {
  readonly user: string;
  readonly uid: number;
  readonly home: string;
}

/** Parse one `getent passwd <user>` line. Null when it is not a passwd row. */
export function parsePasswd(line: string): Passwd | null {
  const f = line.trim().split(":");
  if (f.length < 7) return null;
  const [user, , uidText, , , home] = f;
  const uid = Number(uidText);
  if (!user || !home || !Number.isInteger(uid)) return null;
  return { user, uid, home };
}
